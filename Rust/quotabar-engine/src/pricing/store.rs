//! Owns the pricing data (Swift `ModelPricingStore.swift`): bundled snapshots for an offline first
//! launch, on-disk caches in `<app data>/pricing` (the same files and `state.json` the Swift app
//! wrote, so an upgrade keeps its caches), and hourly revalidation of OpenRouter, LiteLLM, models.dev
//! and the QuotaBar supplement. `current()` never blocks on the network: it serves the freshest data
//! on hand and revalidates on a background thread (stale-while-revalidate).

use super::catalog::PricingCatalog;
use super::codecs::{self, CodecError};
use super::discovery::{DiscoveryState, UnresolvedSink};
use super::resolve::{ModelPricing, RecheckHook};
use super::supplement::PricingSupplement;
use crate::context::CancelToken;
use crate::http::{self, HttpClient, Request};
use crate::{paths, qlog, time};
use serde_json::{json, Value};
use std::collections::HashMap;
use std::path::PathBuf;
use std::sync::{Arc, Mutex, MutexGuard, OnceLock};
use std::time::Duration;

const REFRESH_INTERVAL: f64 = 60.0 * 60.0;
/// Retry a failed source after this long (keeps failure logs from repeating every pass).
pub(super) const FAILURE_RETRY_INTERVAL: f64 = 30.0 * 60.0;
const OPEN_ROUTER_PAGE_LIMIT: i64 = 1_000;
const OPEN_ROUTER_MAX_PAGES: usize = 64;
const FETCH_TIMEOUT: Duration = Duration::from_secs(30);

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum SourceId {
    OpenRouter,
    Litellm,
    ModelsDev,
    Supplement,
}

impl SourceId {
    pub const ALL: [SourceId; 4] = [SourceId::OpenRouter, SourceId::Litellm, SourceId::ModelsDev, SourceId::Supplement];

    pub fn raw(self) -> &'static str {
        match self {
            SourceId::OpenRouter => "openrouter",
            SourceId::Litellm => "litellm",
            SourceId::ModelsDev => "models_dev",
            SourceId::Supplement => "supplement",
        }
    }

    fn from_raw(raw: &str) -> Option<SourceId> {
        SourceId::ALL.into_iter().find(|s| s.raw() == raw)
    }
}

pub fn default_source_urls() -> HashMap<SourceId, String> {
    HashMap::from([
        (SourceId::OpenRouter, "https://openrouter.ai/api/v1/models".to_string()),
        (
            SourceId::Litellm,
            "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json".to_string(),
        ),
        (SourceId::ModelsDev, "https://models.dev/api.json".to_string()),
        (SourceId::Supplement, "https://robinebers.github.io/openusage/pricing_supplement.json".to_string()),
    ])
}

/// The snapshots shipped in the binary (regenerated by `script/update_pricing_snapshots.sh`).
pub fn bundled_data(source: SourceId) -> Option<&'static [u8]> {
    match source {
        SourceId::Supplement => Some(include_bytes!("../../../../Sources/QuotaBar/Resources/pricing_supplement.json")),
        SourceId::Litellm => Some(include_bytes!("../../../../Sources/QuotaBar/Resources/pricing_litellm_snapshot.json")),
        SourceId::ModelsDev => Some(include_bytes!("../../../../Sources/QuotaBar/Resources/pricing_models_dev_snapshot.json")),
        SourceId::OpenRouter => None,
    }
}

#[derive(Clone, Debug, Default, PartialEq)]
pub(super) struct SourceState {
    etag: Option<String>,
    fetched_at: Option<f64>,
    failed_at: Option<f64>,
}

pub struct StoreConfig {
    pub http: Arc<dyn HttpClient>,
    /// `None`: `<app data>/pricing`, resolved on each access so `configure` can run first.
    pub cache_dir: Option<PathBuf>,
    pub now: Arc<dyn Fn() -> f64 + Send + Sync>,
    pub source_urls: HashMap<SourceId, String>,
    pub bundled: Arc<dyn Fn(SourceId) -> Option<&'static [u8]> + Send + Sync>,
}

impl Default for StoreConfig {
    fn default() -> Self {
        StoreConfig {
            http: http::shared(),
            cache_dir: None,
            now: Arc::new(crate::context::now_timestamp),
            source_urls: default_source_urls(),
            bundled: Arc::new(bundled_data),
        }
    }
}

pub(super) struct StoreState {
    loaded: bool,
    pub(super) pricing: Arc<ModelPricing>,
    source_states: HashMap<SourceId, SourceState>,
    pub(super) refresh_running: bool,
    pub(super) discovery: DiscoveryState,
}

pub struct PricingStore {
    pub(super) config: StoreConfig,
    pub(super) state: Mutex<StoreState>,
    pub(super) sink: Arc<UnresolvedSink>,
}

static SHARED: OnceLock<Arc<PricingStore>> = OnceLock::new();

/// The process-wide store every scanner prices through.
pub fn shared() -> &'static Arc<PricingStore> {
    SHARED.get_or_init(|| PricingStore::new(StoreConfig::default()))
}

/// The process-wide store if a provider has priced anything yet (post-refresh hooks must not create
/// it for providers that never price).
pub fn shared_if_initialized() -> Option<&'static Arc<PricingStore>> {
    SHARED.get()
}

impl PricingStore {
    pub fn new(config: StoreConfig) -> Arc<PricingStore> {
        Arc::new(PricingStore {
            config,
            state: Mutex::new(StoreState {
                loaded: false,
                pricing: Arc::new(ModelPricing::default()),
                source_states: HashMap::new(),
                refresh_running: false,
                discovery: DiscoveryState::default(),
            }),
            sink: Arc::new(UnresolvedSink::default()),
        })
    }

    pub(super) fn lock(&self) -> MutexGuard<'_, StoreState> {
        self.state.lock().unwrap_or_else(|e| e.into_inner())
    }

    pub(super) fn now(&self) -> f64 {
        (self.config.now)()
    }

    /// The pricing snapshot for a scan pass. Starts a background refresh when a source is due, unless
    /// this is a menu-bar pass (`skip_model_catalog_refresh`) and every catalogue is already on disk.
    pub fn current(self: &Arc<Self>, skip_model_catalog_refresh: bool) -> Arc<ModelPricing> {
        let mut state = self.lock();
        self.load_if_needed(&mut state);
        let due = SourceId::ALL.iter().any(|s| self.config.source_urls.contains_key(s) && self.is_due(&state, *s));
        if due && !state.refresh_running && !state.discovery.running {
            let catalogs_present =
                SourceId::ALL.iter().all(|s| !self.config.source_urls.contains_key(s) || self.cache_file(*s).exists());
            if !(skip_model_catalog_refresh && catalogs_present) {
                state.refresh_running = true;
                let store = self.clone();
                if !spawn("quotabar-pricing-refresh", move || store.refresh_due_sources()) {
                    state.refresh_running = false;
                }
            }
        }
        let pricing = state.pricing.clone();
        drop(state);
        self.schedule_discovery_if_queued(skip_model_catalog_refresh);
        pricing
    }

    /// Run any due fetches to completion on the calling thread (tests, deterministic refresh points).
    pub fn refresh_now(self: &Arc<Self>) {
        {
            let mut state = self.lock();
            self.load_if_needed(&mut state);
            if state.refresh_running {
                return;
            }
            state.refresh_running = true;
        }
        self.refresh_due_sources();
    }

    pub fn clear_caches(&self) {
        self.lock().pricing.clear_caches();
    }

    fn load_if_needed(&self, state: &mut StoreState) {
        if state.loaded {
            return;
        }
        state.loaded = true;
        state.source_states = self.read_source_states();
        self.rebuild_pricing(state);
    }

    pub(super) fn rebuild_pricing(&self, state: &mut StoreState) {
        let sink = self.sink.clone();
        let hook: RecheckHook = Arc::new(move |name: &str| sink.record(name));
        state.pricing = Arc::new(ModelPricing::new(
            self.load_supplement(),
            self.load_catalog(SourceId::Litellm),
            self.load_catalog(SourceId::ModelsDev),
            self.load_catalog(SourceId::OpenRouter),
            Some(hook),
        ));
        // A fresh snapshot reports fallback-priced names again; keep their miss streaks so unrelated
        // rebuilds cannot hold a model in discovery forever.
        state.discovery.prune_completed(&state.pricing);
    }

    /// Bundled is the base (it ships new pins); the cached feed overlays per key so a fresher feed wins
    /// where it has data, and bundled-only models are never lost. Bundle tombstones stay
    /// authoritative unless a complete, newer feed restores an alias.
    fn load_supplement(&self) -> PricingSupplement {
        let cached = self.read_cache(SourceId::Supplement).and_then(|data| match PricingSupplement::decode(&data) {
            Ok(s) => Some(s),
            Err(error) => {
                qlog!(Warn, "pricing", "cached supplement unreadable, using bundled: {error}");
                None
            }
        });
        let bundled = match (self.config.bundled)(SourceId::Supplement) {
            Some(data) => PricingSupplement::decode(data)
                .map_err(|error| qlog!(Error, "pricing", "bundled pricing_supplement.json unreadable: {error}"))
                .ok(),
            None => {
                qlog!(Error, "pricing", "bundled pricing_supplement.json missing");
                None
            }
        };
        match (cached, bundled) {
            (Some(cached), Some(bundled)) => {
                if is_newer(bundled.updated_at.as_deref(), cached.updated_at.as_deref()) {
                    return cached.merging(&bundled);
                }
                let merged = bundled.merging(&cached);
                let complete_newer = is_newer(cached.updated_at.as_deref(), bundled.updated_at.as_deref())
                    && cached.retired_alias_patterns_are_authoritative;
                merged.preserving_retirements(&bundled, !complete_newer)
            }
            (Some(cached), None) => cached,
            (None, Some(bundled)) => bundled,
            (None, None) => PricingSupplement::default(),
        }
    }

    /// Entries from either the bundle or the cache survive; the newer snapshot wins conflicts.
    fn load_catalog(&self, source: SourceId) -> PricingCatalog {
        let mut catalog = PricingCatalog::default();
        let resource = match source {
            SourceId::Litellm => Some("pricing_litellm_snapshot"),
            SourceId::ModelsDev => Some("pricing_models_dev_snapshot"),
            _ => None,
        };
        if let Some(resource) = resource {
            match (self.config.bundled)(source) {
                Some(data) => match codecs::catalog_from_compact(data) {
                    Ok(bundled) => catalog = bundled,
                    Err(error) => qlog!(Error, "pricing", "bundled {resource}.json unreadable: {error}"),
                },
                None => qlog!(Error, "pricing", "bundled {resource}.json missing"),
            }
        }
        if let Some(data) = self.read_cache(source) {
            match codecs::catalog_from_compact(&data) {
                Ok(cached) => catalog = merge_catalog(&catalog, &cached),
                Err(error) => {
                    let fallback = if source == SourceId::OpenRouter { "using other pricing sources" } else { "using bundled snapshot" };
                    qlog!(Warn, "pricing", "cached {} catalog unreadable, {fallback}: {error}", source.raw());
                }
            }
        }
        catalog
    }

    // MARK: refresh

    /// A stamp in the future (clock set forward, then back) counts as expired, never fresh forever.
    fn is_due(&self, state: &StoreState, source: SourceId) -> bool {
        let entry = state.source_states.get(&source).cloned().unwrap_or_default();
        let now = self.now();
        if let Some(failed) = entry.failed_at {
            let elapsed = now - failed;
            if (0.0..FAILURE_RETRY_INTERVAL).contains(&elapsed) {
                return false;
            }
        }
        match entry.fetched_at {
            None => true,
            Some(fetched) => {
                let elapsed = now - fetched;
                elapsed < 0.0 || elapsed >= REFRESH_INTERVAL
            }
        }
    }

    pub(super) fn failure_retry_blocked(&self, state: &StoreState, source: SourceId) -> bool {
        state.source_states.get(&source).and_then(|s| s.failed_at).is_some_and(|failed| {
            let elapsed = self.now() - failed;
            (0.0..FAILURE_RETRY_INTERVAL).contains(&elapsed)
        })
    }

    /// Expects `refresh_running` already set by the caller; clears it when done.
    fn refresh_due_sources(self: &Arc<Self>) {
        let due: Vec<SourceId> = {
            let state = self.lock();
            SourceId::ALL.into_iter().filter(|s| self.is_due(&state, *s)).collect()
        };
        let mut changed = false;
        let mut attempted_open_router = false;
        for source in due {
            attempted_open_router |= source == SourceId::OpenRouter && self.config.source_urls.contains_key(&source);
            changed |= self.fetch(source);
        }
        let mut guard = self.lock();
        let state = &mut *guard;
        if changed {
            self.rebuild_pricing(state);
            let p = &state.pricing;
            qlog!(
                Info,
                "pricing",
                "pricing refreshed ({} OpenRouter, {} LiteLLM, {} models.dev, {} supplement models)",
                p.open_router.entries.len(),
                p.primary.entries.len(),
                p.secondary.entries.len(),
                p.supplement.pricing.len()
            );
        }
        self.write_source_states(state);
        if attempted_open_router {
            // This fetch already revalidated OpenRouter for every queued name; count it as their
            // attempt instead of repeating the same GET from discovery seconds later.
            let now = self.now();
            state.discovery.absorb_external_attempt(&state.pricing, now);
        }
        state.refresh_running = false;
    }

    /// Fetch one source and update its cache file. Returns true when new data was stored.
    pub(super) fn fetch(&self, source: SourceId) -> bool {
        let Some(url) = self.config.source_urls.get(&source).cloned() else { return false };
        if source == SourceId::OpenRouter {
            self.lock().discovery.note_open_router_attempt(self.now());
            return self.fetch_open_router(&url);
        }
        let etag = self.lock().source_states.get(&source).and_then(|s| s.etag.clone());
        let mut request = Request::get(url).timeout(FETCH_TIMEOUT);
        if let Some(etag) = etag {
            request = request.header("If-None-Match", etag);
        }
        let outcome = match self.config.http.send(&request, &CancelToken::new()) {
            Ok(response) if response.status == 200 => {
                let fetched_at = self.now();
                self.validated_cache_data(source, &response.body, fetched_at)
                    .and_then(|data| self.write_cache(source, &data))
                    .map(|()| Some((response.header("etag").map(str::to_string), fetched_at)))
            }
            Ok(response) if response.status == 304 => Ok(None),
            Ok(response) => Err(format!("HTTP {}", response.status)),
            Err(error) => Err(error.to_string()),
        };
        self.record_outcome(source, outcome)
    }

    /// Every page is fetched before a new snapshot is written; a partial sequence never replaces a
    /// complete catalogue. OpenRouter sends no ETag, so requests are unconditional.
    fn fetch_open_router(&self, base_url: &str) -> bool {
        let outcome = (|| -> Result<Option<(Option<String>, f64)>, String> {
            let mut all: Vec<Value> = Vec::new();
            let mut expected: Option<i64> = None;
            let mut offset = 0i64;
            for page_index in 0..OPEN_ROUTER_MAX_PAGES {
                let url = open_router_page_url(base_url, offset);
                let response = self
                    .config
                    .http
                    .send(&Request::get(url).timeout(FETCH_TIMEOUT), &CancelToken::new())
                    .map_err(|e| e.to_string())?;
                if response.status == 304 && page_index == 0 {
                    return Ok(None);
                }
                if response.status != 200 {
                    return Err(format!("HTTP {}", response.status));
                }
                let page = codecs::open_router_page(&response.body).map_err(|e| e.to_string())?;
                let incomplete = CodecError::IncompleteModelList.to_string();
                if page.models.len() as i64 > OPEN_ROUTER_PAGE_LIMIT
                    || page.total_count < all.len() as i64 + page.models.len() as i64
                    || expected.is_some_and(|e| e != page.total_count)
                {
                    return Err(incomplete);
                }
                expected = Some(page.total_count);
                let page_len = page.models.len() as i64;
                all.extend(page.models);
                if all.len() as i64 == page.total_count {
                    if page.next_offset.is_some() {
                        return Err(incomplete);
                    }
                    let body = serde_json::to_vec(&json!({ "data": all, "total_count": page.total_count, "links": { "next": null } }))
                        .map_err(|e| e.to_string())?;
                    let fetched_at = self.now();
                    let data = self.validated_cache_data(SourceId::OpenRouter, &body, fetched_at)?;
                    self.write_cache(SourceId::OpenRouter, &data)?;
                    return Ok(Some((None, fetched_at)));
                }
                match page.next_offset {
                    Some(next) if (all.len() as i64) < page.total_count && next == offset + page_len && next > offset => offset = next,
                    _ => return Err(incomplete),
                }
            }
            Err(CodecError::IncompleteModelList.to_string())
        })();
        self.record_outcome(SourceId::OpenRouter, outcome)
    }

    /// `Ok(Some((etag, fetched_at)))`: new data stored. `Ok(None)`: not modified. `Err`: failure, the
    /// cached data stays and the source cools off.
    fn record_outcome(&self, source: SourceId, outcome: Result<Option<(Option<String>, f64)>, String>) -> bool {
        let now = self.now();
        let mut state = self.lock();
        let entry = state.source_states.entry(source).or_default();
        match outcome {
            Ok(Some((etag, fetched_at))) => {
                entry.etag = etag;
                entry.fetched_at = Some(fetched_at);
                entry.failed_at = None;
                true
            }
            Ok(None) => {
                entry.fetched_at = Some(now);
                entry.failed_at = None;
                false
            }
            Err(error) => {
                entry.failed_at = Some(now);
                let fallback = if source == SourceId::OpenRouter { "openrouter" } else { source.raw() };
                qlog!(Warn, "pricing", "{fallback} refresh failed, keeping cached data: {error}");
                false
            }
        }
    }

    /// Parse the fetched body (garbage never replaces a good cache) and return the bytes to persist:
    /// compacted for the big catalogs, verbatim for the supplement.
    fn validated_cache_data(&self, source: SourceId, body: &[u8], fetched_at: f64) -> Result<Vec<u8>, String> {
        let mut catalog = match source {
            SourceId::Litellm => codecs::catalog_from_litellm(body),
            SourceId::ModelsDev => codecs::catalog_from_models_dev(body),
            SourceId::OpenRouter => codecs::catalog_from_open_router(body),
            SourceId::Supplement => {
                PricingSupplement::decode(body)?;
                return Ok(body.to_vec());
            }
        }
        .map_err(|e| e.to_string())?;
        catalog.retrieved_at = Some(time::format_iso8601(fetched_at));
        Ok(codecs::compact_data(&catalog))
    }

    // MARK: disk

    pub(super) fn cache_dir(&self) -> PathBuf {
        self.config.cache_dir.clone().unwrap_or_else(|| paths::app_data().join("pricing"))
    }

    pub(super) fn cache_file(&self, source: SourceId) -> PathBuf {
        self.cache_dir().join(format!("{}.json", source.raw()))
    }

    fn read_cache(&self, source: SourceId) -> Option<Vec<u8>> {
        std::fs::read(self.cache_file(source)).ok()
    }

    fn write_cache(&self, source: SourceId, data: &[u8]) -> Result<(), String> {
        std::fs::create_dir_all(self.cache_dir()).map_err(|e| e.to_string())?;
        paths::write_atomic(&self.cache_file(source), data).map_err(|e| e.to_string())
    }

    /// `state.json` is Swift's encoding of `[SourceID: SourceState]`: a flat `[key, value, ...]` array
    /// with dates as seconds since 2001-01-01.
    fn read_source_states(&self) -> HashMap<SourceId, SourceState> {
        let Ok(data) = std::fs::read(self.cache_dir().join("state.json")) else { return HashMap::new() };
        let Ok(Value::Array(items)) = serde_json::from_slice::<Value>(&data) else { return HashMap::new() };
        let date = |v: Option<&Value>| v.and_then(Value::as_f64).map(|s| s + time::REFERENCE_DATE_UNIX);
        items
            .chunks(2)
            .filter_map(|pair| {
                let source = SourceId::from_raw(pair.first()?.as_str()?)?;
                let value = pair.get(1)?.as_object()?;
                Some((
                    source,
                    SourceState {
                        etag: value.get("etag").and_then(Value::as_str).map(str::to_string),
                        fetched_at: date(value.get("fetchedAt")),
                        failed_at: date(value.get("failedAt")),
                    },
                ))
            })
            .collect()
    }

    pub(super) fn write_source_states(&self, state: &StoreState) {
        let mut items = Vec::new();
        for source in SourceId::ALL {
            let Some(entry) = state.source_states.get(&source) else { continue };
            let mut value = serde_json::Map::new();
            if let Some(etag) = &entry.etag {
                value.insert("etag".into(), json!(etag));
            }
            if let Some(at) = entry.fetched_at {
                value.insert("fetchedAt".into(), json!(at - time::REFERENCE_DATE_UNIX));
            }
            if let Some(at) = entry.failed_at {
                value.insert("failedAt".into(), json!(at - time::REFERENCE_DATE_UNIX));
            }
            items.push(json!(source.raw()));
            items.push(Value::Object(value));
        }
        let result = std::fs::create_dir_all(self.cache_dir())
            .and_then(|()| paths::write_atomic(&self.cache_dir().join("state.json"), &serde_json::to_vec(&items).unwrap_or_default()));
        if let Err(error) = result {
            qlog!(Warn, "pricing", "could not persist pricing fetch state: {error}");
        }
    }
}

/// Older writers omitted `retrieved_at`; a dated bundle is newer than those caches. When both are
/// absent the cache keeps priority.
fn merge_catalog(bundled: &PricingCatalog, cached: &PricingCatalog) -> PricingCatalog {
    if bundled.retrieved_at.is_none() && cached.retrieved_at.is_none() {
        return bundled.merging(cached);
    }
    if is_newer(cached.retrieved_at.as_deref(), bundled.retrieved_at.as_deref()) {
        bundled.merging(cached)
    } else {
        cached.merging(bundled)
    }
}

/// Parsed-date comparison (`YYYY-MM-DD` or full ISO); lexicographic only when parsing fails. A
/// missing date counts as oldest.
pub(super) fn is_newer(lhs: Option<&str>, rhs: Option<&str>) -> bool {
    let Some(lhs) = lhs else { return false };
    let Some(rhs) = rhs else { return true };
    match (time::parse_feed_date(lhs), time::parse_feed_date(rhs)) {
        (Some(l), Some(r)) => l > r,
        _ => lhs > rhs,
    }
}

fn open_router_page_url(base: &str, offset: i64) -> String {
    let (path, query) = base.split_once('?').unwrap_or((base, ""));
    let mut params: Vec<&str> =
        query.split('&').filter(|p| !p.is_empty() && !p.starts_with("limit=") && !p.starts_with("offset=")).collect();
    let tail = format!("limit={OPEN_ROUTER_PAGE_LIMIT}&offset={offset}");
    params.push(&tail);
    format!("{path}?{}", params.join("&"))
}

/// Start a background thread; false (logged) when the OS refuses one.
pub(super) fn spawn(name: &str, work: impl FnOnce() + Send + 'static) -> bool {
    match std::thread::Builder::new().name(name.to_string()).spawn(work) {
        Ok(_) => true,
        Err(error) => {
            qlog!(Error, "pricing", "could not start {name} thread: {error}");
            false
        }
    }
}
